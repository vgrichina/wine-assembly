#!/usr/bin/env node
// Generate lib/region-map.generated.js — the JS mirror of the fixed memory map
// declared in src/00-regions.wat (docs/watx-region-safety-design.md §6).
//
// WHY THIS EXISTS
// The bases in src/00-regions.wat are an ABI: lib/host-imports.js, lib/dll-loader.js,
// lib/storage.js, lib/filesystem.js, lib/guest-rpc.js and friends all held their own
// copies of them — 43 raw literals plus ~24 open-coded `- imageBase + 0x12000` g2w
// recomputations, each an independent chance to drift. A value generated from the
// declaration cannot drift from it, so the copies become reads.
//
// WHY IT DOES NOT PARSE ANYTHING ITSELF
// tools/check-region-decls.js is the single reader of the declarations, and
// tools/region-census.js already imports it for exactly this reason: a generator
// with its own parser would be a second grammar, and the mirror could then be
// generated from a reading of the map that the gate does not share. So this reads
// collectDeclarations() and collectGlobals() and does nothing but format.
//
// Usage:
//   node tools/gen-region-map.js            regenerate the mirror
//   node tools/gen-region-map.js --check    fail if the committed mirror is stale
//
// The --check mode is the build gate (same shape as tools/gen_dispatch.js --check).

const fs = require('fs');
const path = require('path');
const { collectDeclarations, collectGlobals } = require('./check-region-decls.js');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'lib', 'region-map.generated.js');
const REL = 'lib/region-map.generated.js';

// Emitted with a numeric separator (`0x0001_2000`), which is exactly the value a
// plain `0x00012000` is and reads the same, for two reasons. It groups an eight
// digit address the way the map is actually read, and it keeps the generated
// mirror out of tools/region-census.js's raw-literal odometer, whose pattern is
// `0x[0-9a-f]{4,8}` — the mirror is not a *copy* of the map, it is the map
// rendered for JS, so counting its 160 entries as debt would drown the signal the
// census exists to give. (If the census gains an explicit exemption for generated
// files, plain hex here becomes fine again.)
const hex = (n) => {
  const digits = (n >>> 0).toString(16).toUpperCase().padStart(8, '0');
  return `0x${digits.slice(0, 4)}_${digits.slice(4)}`;
};

function render() {
  const decls = collectDeclarations();
  const globals = collectGlobals();

  // A declaration this generator cannot read is a mirror entry that would be
  // silently wrong, so refuse rather than emit it. check-region-decls.js reports
  // the same problems with better messages; this only has to not guess.
  const bad = [];
  const seen = new Set();
  for (const d of decls) {
    const where = `${d.file}:${d.line}`;
    if (seen.has(d.name)) bad.push(`$${d.name} declared more than once (${where})`);
    seen.add(d.name);
    for (const pe of d.parseErrors) bad.push(`$${d.name} (${where}): ${pe}`);
    if (d.base === null || d.size === null) {
      bad.push(`$${d.name} (${where}) has no readable base/extent`);
    }
  }
  if (bad.length) {
    for (const b of bad) console.error(`gen-region-map: ${b}`);
    console.error('gen-region-map: refusing to generate a mirror of declarations ' +
      'it cannot read; run node tools/check-region-decls.js.');
    process.exit(1);
  }

  // Deterministic order: by base, then by name, so the emitted file is a function
  // of the declarations and a reordering in 00-regions.wat produces no diff here.
  const ordered = [...decls].sort((a, b) => a.base - b.base || a.name.localeCompare(b.name));

  const lines = [];
  lines.push('// GENERATED by tools/gen-region-map.js — DO NOT EDIT.');
  lines.push('//');
  lines.push('// The JS mirror of the fixed memory map declared in src/00-regions.wat');
  lines.push('// (docs/watx-region-safety-design.md §6). Every entry is frozen and every');
  lines.push('// value comes from a `region.declare-fixed` form, so a JS consumer that reads');
  lines.push('// it cannot hold a copy of the map that drifts from the WAT one.');
  lines.push('//');
  lines.push('// To change an address, change the declaration in src/00-regions.wat (and the');
  lines.push('// $NAME / $NAME_SIZE globals it mirrors), then run:');
  lines.push('//     node tools/gen-region-map.js');
  lines.push('//');
  lines.push('// BOTH HOSTS. This is a classic script as well as a CommonJS module: Node gets');
  lines.push('// `require(\'./region-map.generated\')`, the browser and web workers get the');
  lines.push('// global `RegionMap` (index.html must load it before any lib/ consumer;');
  lines.push('// lib/guest-worker.js importScripts() it for the worker side).');
  lines.push('(function (root) {');
  lines.push('  \'use strict\';');
  lines.push('');
  lines.push('  // REGIONS.NAME = { name, base, size, end, within }');
  lines.push('  const REGIONS = {');
  for (const d of ordered) {
    const end = (d.base + d.size) >>> 0;
    const within = d.within ? `'${d.within}'` : 'null';
    lines.push(`    ${d.name}: { name: '${d.name}', base: ${hex(d.base)}, ` +
      `size: ${hex(d.size)}, end: ${hex(end)}, within: ${within} },`);
  }
  lines.push('  };');
  lines.push('');
  lines.push('  // The `(global $NAME i32 ...)` values the declarations mirror, for the few');
  lines.push('  // consumers that want a bare number: BASE.GUEST_BASE, SIZE.DX_OBJECTS.');
  lines.push('  const BASE = {};');
  lines.push('  const SIZE = {};');
  lines.push('  const END = {};');
  lines.push('  for (const r of Object.values(REGIONS)) {');
  lines.push('    Object.freeze(r);');
  lines.push('    BASE[r.name] = r.base; SIZE[r.name] = r.size; END[r.name] = r.end;');
  lines.push('  }');
  lines.push('');
  lines.push('  // Guest↔wasm translation, the one derivation every JS host repeats');
  lines.push('  // (docs/watx-region-safety-design.md §5 pattern 8). Kept here so the ~24');
  lines.push('  // open-coded `- imageBase + 0x12000` copies have one thing to call.');
  lines.push('  const GUEST_BASE = REGIONS.GUEST_BASE.base;');
  lines.push('  const g2wOffset = (imageBase) => (GUEST_BASE - (imageBase >>> 0)) | 0;');
  lines.push('  const g2w = (guestAddr, imageBase) =>');
  lines.push('    (((guestAddr >>> 0) - (imageBase >>> 0) + GUEST_BASE) >>> 0);');
  lines.push('');
  lines.push('  const api = Object.freeze({');
  lines.push('    REGIONS: Object.freeze(REGIONS),');
  lines.push('    BASE: Object.freeze(BASE), SIZE: Object.freeze(SIZE), END: Object.freeze(END),');
  lines.push('    GUEST_BASE, g2w, g2wOffset,');
  lines.push('  });');
  lines.push('');
  lines.push('  if (typeof module !== \'undefined\' && module.exports) module.exports = api;');
  lines.push('  if (root) root.RegionMap = api;');
  lines.push('})(typeof globalThis !== \'undefined\' ? globalThis :');
  lines.push('   typeof self !== \'undefined\' ? self : this);');
  lines.push('');

  // A mirror of a declaration whose $NAME global disappeared would be a mirror of
  // nothing; check-region-decls.js fails on that too, but this generator writes the
  // file the build ships, so it says so in its own voice.
  const orphans = ordered.filter(d => !globals.has(d.name)).map(d => d.name);
  if (orphans.length) {
    console.error(`gen-region-map: ${orphans.length} declared region(s) have no ` +
      `(global $NAME i32 ...) behind them: ${orphans.join(', ')}`);
    process.exit(1);
  }

  return { text: lines.join('\n'), count: ordered.length };
}

function main() {
  const { text, count } = render();
  const check = process.argv.includes('--check');
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;

  if (check) {
    if (current === text) {
      console.log(`gen-region-map: ${REL} is current (${count} regions)`);
      return;
    }
    console.error(`gen-region-map: ${REL} is stale — regenerate it with ` +
      `\`node tools/gen-region-map.js\` and commit the result.`);
    process.exit(1);
  }

  if (current === text) {
    console.log(`gen-region-map: ${REL} unchanged (${count} regions)`);
    return;
  }
  fs.writeFileSync(OUT, text);
  console.log(`gen-region-map: wrote ${REL} (${count} regions)`);
}

module.exports = { render };
if (require.main === module) main();

#!/usr/bin/env node
'use strict';
const { bootRenderHarness } = require('../test/render-helper');

const blocks = new Map([
  [0x00535c20, [
    0x89,0x35,0x50,0x50,0x77,0x00,0x33,0xc0,0x89,0x3d,0x54,0x50,0x77,0x00,
    0x8a,0x06,0x2b,0x3d,0x20,0x50,0x77,0x00,0x8b,0xc8,0x46,0x83,0xe0,0x0f,
    0x8b,0x1d,0x3c,0x50,0x77,0x00,0xff,0x24,0x85,0x00,0x44,0x53,0x00]],
  [0x00535e00, [0xc1,0xe9,0x04,0x75,0x03,0x8a,0x0e,0x46]],
  [0x00535e08, [0x8b,0xd7,0x03,0xd1,0x4a,0x3b,0x53,0x08,0x7c,0x6a]],
  [0x00535e7c, [0x8b,0x3d,0x54,0x50,0x77,0x00,0x46,0x03,0xf9,0xe9,0x96,0xfd,0xff,0xff]],
]);

(async () => {
  const { exports: e, memory } = await bootRenderHarness();
  const u8 = new Uint8Array(memory.buffer), u32 = new Uint32Array(memory.buffer);
  const guestBase = e.get_guest_base() >>> 0, imageBase = e.get_image_base() >>> 0;
  const wa = ga => (ga - imageBase + guestBase) >>> 0;
  for (const [ga, bytes] of blocks) u8.set(bytes, wa(ga));
  e.set_esi(0x200000); e.set_edi(0x340001); e.set_ecx(0x20); e.set_ebx(0x300000);
  e.guest_write32(0x775020, 0); e.guest_write32(0x77503c, 0x300000);
  e.guest_write32(0x300008, 0x7fffffff); e.guest_write32(0x534400 + 0x0b * 4, 0x535e00);
  for (const ga of blocks.keys()) {
    e.set_eip(ga); e.run(1);
    const cache = 0x07152000 + (((ga >>> 2) & 0xfff) * 8);
    const thread = u32[(cache + 4) >>> 2] >>> 0;
    const words = Array.from(u32.slice(thread >>> 2, (thread >>> 2) + 40), x => '0x' + x.toString(16));
    console.log('0x' + ga.toString(16), 'thread=0x' + thread.toString(16), words.join(' '));
  }
})().catch(e => { console.error(e); process.exit(1); });
